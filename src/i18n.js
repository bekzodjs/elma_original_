const clean = s => (s || '').replace(/\s+/g, ' ').trim()

function walk(el, lang) {
  if (!el || el.nodeType !== 1) return
  if (el.matches('header, .header, script, style')) return
  if (el.hasAttribute('data-i18n-skip')) return

  for (const node of Array.from(el.childNodes)) {
    if (node.nodeType === 3) {
      const raw = clean(node.nodeValue)
      if (!raw) continue
      if (!node.__elmaKey) node.__elmaKey = ruToUz[raw] || raw
      const key = node.__elmaKey
      const next = lang === 'ru' ? (uzToRu[key] || key) : key
      if (clean(node.nodeValue) !== next) node.nodeValue = next
    } else if (node.nodeType === 1) {
      for (const attr of ['placeholder','title','aria-label']) {
        if (!node.hasAttribute(attr)) continue
        const raw = clean(node.getAttribute(attr))
        const key = ruToUz[raw] || raw
        node.setAttribute(attr, lang === 'ru' ? (uzToRu[key] || key) : key)
      }
      if (!node.matches('input, textarea')) walk(node, lang)
    }
  }
}

export const i18nDirective = {
  mounted(el, binding) { queueMicrotask(() => walk(el, binding.value || 'uz')) },
  updated(el, binding) { queueMicrotask(() => walk(el, binding.value || 'uz')) }
}
